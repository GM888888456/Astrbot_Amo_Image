def match_scene(place: str) -> str:
    """地点 → 固定环境描述。命中不了就按地点字符串稳定地选一条兜底。"""
    text = str(place or "").strip()
    if not text:
        return ""
    for words, scene in SCENE_MAP:
        if any(word in text for word in words):
            return scene
    index = int(hashlib.sha256(text.encode("utf-8")).hexdigest()[:8], 16)
    return FALLBACK_SCENES[index % len(FALLBACK_SCENES)]


#: 地点彻底未知时用的中性环境：必须有一条，否则模型会把背景画成任何东西。
NEUTRAL_SCENE = (
    "室内，浅色墙面，木质地板，靠墙一张木桌，桌上有一盏台灯和几本书，"
    "侧窗透进自然光"
)


def scene_anchor(place: str, fallback_scene: str = "") -> str:
    """给提示词用的环境块，**永远不为空**。

    优先级：地点能识别 → 用对应场景；识别不了 → 用上次记住的；再没有 → 用中性
    室内场景。留空就等于让模型自由发挥，背景会一张一个样。
    """
    scene = match_scene(place) or str(fallback_scene or "").strip() or NEUTRAL_SCENE
    return "环境：" + scene + "。" + ENV_LOCK


def pose_clause(selfie: bool, with_prop: bool = False) -> str:
    if not selfie:
        return OTHER_POSE
    return SELFIE_POSE_WITH_PROP if with_prop else SELFIE_POSE


def split_prompts(text: str, limit: int = 4) -> list[str]:
    """一条指令里要好几张图时，按换行 / 分号 / 竖线切开。

    只切明确的分隔符，不猜「和」——「猫和狗」是一张图，不是两张。
    """
    raw = str(text or "")
    for sep in ("\n", "；", ";", "|", "｜"):
        raw = raw.replace(sep, "\u0000")
    parts = [item.strip() for item in raw.split("\u0000")]
    return [item for item in parts if item][: max(1, int(limit or 1))]
