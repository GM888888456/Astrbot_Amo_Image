"""一致性：同一张脸、同一个环境、同一个姿势。

文生图最难看出来的问题不是画得丑，是「每张都在漂」：

* 上一张还是写字楼，下一张变成街边，招牌还不一样；
* 上一张是这张脸，下一张换了个人；
* 自拍却出现一只手举着手机，或者干脆抱臂站着。

这里把这些约束从主逻辑里拆出来，做成可以单独测的纯函数：

1. ``scene_anchor()`` —— 同一个地点永远给同一段环境描述，换个地点才换环境；
2. ``face_clause()`` —— 脸的锁定句，跟着提示词一起进模型；
3. ``pose_clause()`` —— 自拍/他拍的姿势约束（手机不能入镜、不许抱臂）；
4. ``split_prompts()`` —— 一条指令里要好几张时怎么切。

它不碰网络、不碰事件，只负责把话说对。
"""

